// CLABE (México): 3 banco + 3 plaza + 11 cuenta + dígito de control (pesos 3, 7, 1).
export function clabeCheck(d17) {
  const w = [3, 7, 1];
  const sum = d17.split('').reduce((a, c, i) => a + ((Number(c) * w[i % 3]) % 10), 0);
  return String((10 - (sum % 10)) % 10);
}
export function makeClabe(cuenta, banco = '999', plaza = '180') {
  const d17 = `${banco}${plaza}${String(cuenta).padStart(11, '0')}`;
  return d17 + clabeCheck(d17);
}
export function validClabe(c) { return /^\d{18}$/.test(c) && clabeCheck(c.slice(0, 17)) === c[17]; }

// IBAN (ES): ES + 2 dígitos de control (mod 97) + entidad 9999 + oficina 0001 + DC 00 + cuenta.
function mod97(s) { let r = 0; for (const ch of s) r = (r * 10 + Number(ch)) % 97; return r; }
const ibanDigits = (s) => s.toUpperCase().replace(/[A-Z]/g, (c) => String(c.charCodeAt(0) - 55));
export function makeIban(cuenta, country = 'ES') {
  const bban = `99990001${'00'}${String(cuenta).padStart(10, '0')}`;
  const check = String(98 - mod97(ibanDigits(`${bban}${country}00`))).padStart(2, '0');
  return `${country}${check}${bban}`;
}
export function validIban(iban) {
  const s = String(iban).replace(/\s+/g, '').toUpperCase();
  return /^[A-Z]{2}\d{2}[A-Z0-9]{10,30}$/.test(s) && mod97(ibanDigits(s.slice(4) + s.slice(0, 4))) === 1;
}

